"""Dataset builder orchestrator.

Coordinates generation, validation, leak-free splitting, baseline modeling,
and artifact serialization for the machine learning dataset.
"""

from datetime import datetime, timezone
import json
from pathlib import Path
from typing import Dict, Optional, Union
import pandas as pd

from dataset.generator import DatasetGenerator
from dataset.validation import validate_dataset
from dataset.splitter import split_dataset
from dataset.baseline import NormalBaseline
from dataset.schema import FEATURE_COLUMNS, METADATA_COLUMNS, TARGET_COLUMN, VALID_SCENARIOS


DATASET_VERSION: str = "1.0.0"


def build_processed_dataset(
    samples_per_class: int = 1000,
    seed: int = 42,
    output_dir: Union[str, Path] = "dataset/processed",
    train_ratio: float = 0.70,
    val_ratio: float = 0.15,
    test_ratio: float = 0.15,
    verbose: bool = True,
) -> Dict[str, Path]:
    """Execute complete dataset generation, validation, splitting, and export pipeline.

    Args:
        samples_per_class: Number of events per scenario (default 1000).
        seed: Base random seed for reproducibility.
        output_dir: Directory where processed CSVs and metadata will be saved.
        train_ratio: Proportion for training set (default 0.70).
        val_ratio: Proportion for validation set (default 0.15).
        test_ratio: Proportion for test set (default 0.15).
        verbose: Whether to log execution details to stdout.

    Returns:
        Dictionary mapping artifact names to their saved file Paths.
    """
    out_dir = Path(output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    if verbose:
        print("=" * 75)
        print("STEP 3: SYNTHETIC ML DATASET BUILDER PIPELINE")
        print("=" * 75)

    # 1. Generate full raw feature dataset
    generator = DatasetGenerator(seed=seed)
    df_all = generator.generate_dataset(samples_per_class=samples_per_class, verbose=verbose)

    # 2. Perform validation checks
    if verbose:
        print("[Builder] Validating generated dataset integrity...")
    val_summary = validate_dataset(df_all, expected_samples_per_class=samples_per_class)
    if verbose:
        print(f"[Builder] Validation passed: {val_summary['status']} ({val_summary['total_samples']} samples)")

    # 3. Perform stratified, leak-free train / validation / test partition
    if verbose:
        print(f"[Builder] Splitting dataset: {train_ratio*100:.0f}% train, {val_ratio*100:.0f}% val, {test_ratio*100:.0f}% test...")
    train_df, val_df, test_df = split_dataset(
        df_all,
        train_ratio=train_ratio,
        val_ratio=val_ratio,
        test_ratio=test_ratio,
        random_state=seed,
    )
    if verbose:
        print(f"  -> Train set:       {len(train_df)} rows")
        print(f"  -> Validation set:  {len(val_df)} rows")
        print(f"  -> Test set:        {len(test_df)} rows")

    # 4. Fit NORMAL structural baseline exclusively on NORMAL training data
    if verbose:
        print("[Builder] Establishing NORMAL structural baseline on training data...")
    baseline = NormalBaseline.fit(train_df)

    # 5. Save all processed CSV artifacts
    saved_paths: Dict[str, Path] = {}

    all_path = out_dir / "all_features.csv"
    df_all.to_csv(all_path, index=False, float_format="%.6f")
    saved_paths["all_features"] = all_path

    train_path = out_dir / "train.csv"
    train_df.to_csv(train_path, index=False, float_format="%.6f")
    saved_paths["train"] = train_path

    val_path = out_dir / "validation.csv"
    val_df.to_csv(val_path, index=False, float_format="%.6f")
    saved_paths["validation"] = val_path

    test_path = out_dir / "test.csv"
    test_df.to_csv(test_path, index=False, float_format="%.6f")
    saved_paths["test"] = test_path

    baseline_path = out_dir / "baseline_normal.csv"
    baseline.to_csv(baseline_path)
    saved_paths["baseline_normal"] = baseline_path

    # 6. Generate dataset metadata JSON
    metadata = {
        "dataset_version": DATASET_VERSION,
        "disclaimer": (
            "These data are generated by a physics-inspired simulation for software development "
            "and algorithm validation. They do not represent measurements from real bridges or "
            "certified structural-health-monitoring data."
        ),
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "generation_seed": seed,
        "samples_per_class": samples_per_class,
        "total_samples": len(df_all),
        "scenarios": VALID_SCENARIOS,
        "class_counts": df_all[TARGET_COLUMN].value_counts().to_dict(),
        "split_counts": {
            "train": len(train_df),
            "validation": len(val_df),
            "test": len(test_df),
        },
        "split_ratios": {
            "train": train_ratio,
            "validation": val_ratio,
            "test": test_ratio,
        },
        "feature_count": len(FEATURE_COLUMNS),
        "feature_names": FEATURE_COLUMNS,
        "metadata_columns": METADATA_COLUMNS,
        "target_column": TARGET_COLUMN,
    }

    meta_path = out_dir / "dataset_metadata.json"
    with open(meta_path, "w", encoding="utf-8") as f:
        json.dump(metadata, f, indent=2)
    saved_paths["metadata"] = meta_path

    if verbose:
        print("[Builder] All artifacts saved successfully:")
        for name, p in saved_paths.items():
            print(f"  [+] {name:16s} -> {p.resolve()}")
        print("=" * 75)

    return saved_paths


if __name__ == "__main__":
    build_processed_dataset(samples_per_class=1000, seed=42)
